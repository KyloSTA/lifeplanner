let last = -1;
/** Tire une citation. mode = 'random' (une des 3 catégories au hasard) ou une catégorie précise. */
export function pick(mode = 'random') {
  const cat = mode in CATS ? mode : Object.keys(CATS)[Math.floor(Math.random() * 3)];
  const pool = QUOTES.filter((q) => q.cat === cat && q.id !== last);
  const q = pool[Math.floor(Math.random() * pool.length)];
  last = q.id;
  return q;
}
